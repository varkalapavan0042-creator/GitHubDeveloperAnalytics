@app.route("/api/github/<username>/repos")
@limiter.limit("20 per minute")
def github_repositories(username):
    result = []
    total_stars = 0
    total_forks = 0
    total_size = 0
    languages = {}
    # Limit to 10 pages / 1,000 repositories per request to avoid unbounded API calls.
    max_pages = 10

    for page in range(1, max_pages + 1):
        response, error = github_get(
            f"users/{username}/repos",
            {
                "per_page": 100,
                "page": page,
                "sort": "updated",
                "type": "owner",
            },
        )

        if error:
            return jsonify({"error": error}), 502
        if response.status_code == 404:
            return jsonify({"error": "GitHub user not found."}), 404
        if response.status_code == 403:
            if response.headers.get("X-RateLimit-Remaining") == "0" or (
                "rate limit" in response.text.lower()
            ):
                return jsonify({
                    "error": "GitHub API rate limit reached. Please try again later."
                }), 429
            return jsonify({"error": "GitHub denied this repository request."}), 502
        if response.status_code != 200:
            return jsonify({"error": "Could not fetch repositories."}), 502

        repos = response.json()
        for repo in repos:
            language = repo.get("language")
            if language:
                languages[language] = languages.get(language, 0) + 1

            stars = repo.get("stargazers_count", 0)
            forks = repo.get("forks_count", 0)
            size = repo.get("size", 0)
            total_stars += stars
            total_forks += forks
            total_size += size

            result.append({
                "name": repo.get("name"),
                "description": repo.get("description"),
                "language": language,
                "stars": stars,
                "forks": forks,
                "size": size,
                "updated_at": repo.get("updated_at"),
                "url": repo.get("html_url"),
            })

        if len(repos) < 100:
            break

    return jsonify({
        "repositories": result,
        "analytics": {
            "total_repositories": len(result),
            "total_stars": total_stars,
            "total_forks": total_forks,
            "total_size": total_size,
            "languages": languages,
        },
    })



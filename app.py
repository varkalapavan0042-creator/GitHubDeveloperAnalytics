@app.route("/reset-password/<token>", methods=["GET", "POST"])
@limiter.limit("10 per minute")
def reset_password(token):
    record = get_valid_reset_record(token)
    if record is None:
        flash(
            "This password-reset link is invalid, expired, or already used.",
            "error",
        )
        return redirect(url_for("forgot_password"))

    if request.method == "POST":
        password = request.form.get("password", "")
        confirm_password = request.form.get("confirm_password", "")

        if len(password) < 8:
            flash("Password must be at least 8 characters.", "error")
            return render_template("reset_password.html", token=token)

        if password != confirm_password:
            flash("Passwords do not match.", "error")
            return render_template("reset_password.html", token=token)

        now = int(time.time())
        token_hash = hash_reset_token(token)

        # Transaction + row lock prevents concurrent reuse of the same token.
        with get_db() as db:
            current_record = db.execute(
                """
                SELECT id, user_id
                FROM password_reset_tokens
                WHERE token_hash = %s
                  AND used_at IS NULL
                  AND expires_at > %s
                FOR UPDATE
                """,
                (token_hash, now),
            ).fetchone()

            if current_record is None:
                flash(
                    "This password-reset link is invalid, expired, or already used.",
                    "error",
                )
                return redirect(url_for("forgot_password"))

            db.execute(
                "UPDATE users SET password_hash = %s WHERE id = %s",
                (generate_password_hash(password), current_record["user_id"]),
            )
            db.execute(
                """
                UPDATE password_reset_tokens
                SET used_at = %s
                WHERE user_id = %s AND used_at IS NULL
                """,
                (now, current_record["user_id"]),
            )

        flash(
            "Password reset successful. Please log in with your new password.",
            "success",
        )
        return redirect(url_for("login"))

    return render_template("reset_password.html", token=token)


